#!/usr/bin/env python3
"""Write docs/HARVEST.md from the catalogue: module counts, the compile gate's results and what was left out.
Run after the harvest scripts and after pulling gate/results/compile. Standard library only."""
import collections, glob, json, os, tomllib
REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
ORIGINS = ['strixfold', 'gufo', 'hipfire']
KINDS = ['kernel', 'format', 'executor', 'runtime', 'serve', 'tool']


def load(p):
    with open(p, 'rb') as f:
        return tomllib.load(f)


mods = collections.defaultdict(list)
for p in sorted(glob.glob(os.path.join(REPO, 'catalog/*/*/*/module.toml'))):
    m = load(p)
    mods[m['provenance']['origin']].append(m)
res = {}
for p in glob.glob(os.path.join(REPO, 'gate/results/compile/*.json')):
    j = json.load(open(p))
    res[j['module']] = j
o = []
w = o.append
w('# Harvest: phase 2, the catalogue beyond strixite')
w('')
w('Generated by `docs/harvest/make_harvest_md.py` from the manifests and `gate/results/compile`; edit the script, not this file.')
w('')
w('## What is in the catalogue')
w('')
w('| origin | commit | licence | ' + ' | '.join(KINDS) + ' | modules | files |')
w('|---|---|---|' + '---|' * (len(KINDS) + 2))
for og in ORIGINS:
    oc = load(os.path.join(REPO, 'catalog', og, 'ORIGIN.toml'))
    hv = json.load(open(os.path.join(REPO, 'catalog', og, 'HARVEST.json')))
    c = collections.Counter(m['kind'] for m in mods[og])
    w(f"| {og} | `{oc['commit']}` | {oc['licence']['spdx']} | " + ' | '.join(str(c.get(k, 0)) for k in KINDS) + f" | {len(mods[og])} | {hv['files']} |")
for og in ('sglang', 'halogen'):
    oc = load(os.path.join(REPO, 'catalog', og, 'ORIGIN.toml'))
    w(f"| {og} | `{oc['commit']}` | {oc['licence']['spdx']} | " + ' | '.join('-' for _ in KINDS) + ' | 0 (`harvest = "none"`) | 0 |')
w('')
w('`catalog/strixite` (105 modules) belongs to phase 1 and is not described here.')
w('')
w('Sources are copied verbatim to `catalog/<origin>/<kind>/<name>/src/<origin-relative path>`. `flerp diff-origin --origin <o> <checkout>`')
w('proves it against the reference checkouts: gufo 542 of 542 and hipfire 1,522 of 1,522 files byte-identical. StrixFold is checked on control-node')
w('against `git archive <commit>` of the pod tree `/data/pod/plans/strixfold/fork`, every file byte-identical (`gate/results/dsv41-flash.strixfold-tp2/diff-origin.txt`).')
w('Its `zig/build/*.zig` are missing from the laptop reference copy (it excluded directories named `build`) and come from the pod tree by way of')
w('`~/Code/strixflerp-upstream-supplement/strixfold/zig/build`. This repository\'s `.gitignore` has the same rule (`build/`), so the three files')
w('were not committed in phase 2; they are tracked since phase 3 (`git add -f`).')
w('')
w('Authors: a StrixFold module lists `pod` when one of the pod\'s commits on top of Shoestring-dev 88ea779 touched one of its files')
w('(`git diff --name-only 88ea779 HEAD` on the pod tree: rdma_proxy.zig, tcp_coll.zig, tcp_proxy.zig, native.zig, fabric/verbs.zig,')
w('zig/build/{cuda,hip_dsv41}.zig, tools/dsv41-hip/rdma_check.py among the harvested files). gufo and hipfire carry no pod patches.')
w('')
w('## How it was made, and how to redo it')
w('')
w('```')
w('python3 docs/harvest/harvest_strixfold.py     # each script rebuilds catalog/<origin> from the reference checkout')
w('python3 docs/harvest/harvest_gufo.py')
w('python3 docs/harvest/harvest_hipfire.py')
w('tools/pod-sync.sh && tools/pod-run.sh \'python3 gate/compile/run.py\' && tools/pod-pull.sh gate/results')
w('python3 docs/harvest/harvest_<origin>.py      # again: gate.status = "builds" is written from gate/results/compile')
w('python3 docs/harvest/make_harvest_md.py && python3 flerp check')
w('```')
w('')
w('- `docs/harvest/harvestlib.py`: copying, manifest writing, include-derived `requires`, the `unharvested` list for `flerp diff-origin`.')
w('- `docs/harvest/incgraph.py`: `#include` closure, used to give shared headers to header-only modules (gufo, hipfire).')
w('- `docs/harvest/hipfire_units.py`: recovers hipfire\'s compile units from the Rust source constants and sorts kernel sources into families.')
w('- `docs/harvest/hipfire_exclusions.py`: turns compile failures with a known cause into `docs/harvest/data/hipfire/not_gfx1151.json`.')
w('- `docs/harvest/data/strixfold/`: `aot.json` (the Triton kit manifest), `tri-SHA256SUMS` and the HIP kit manifest, fetched from control-node')
w('  (`/data/pod/plans/af9276f296/tri-kit-gfx1151`, `/data/pod/plans/strixfold/fork/zig-out/native-hip/test/dsv41-kit`).')
w('')
w('## Compile gate')
w('')
w('`gate/compile/run.py` on control-node compiles every `hip-c++` kernel module whose `[gate].compile` is `standalone`, with the command')
w('its origin uses (`catalog/<origin>/ORIGIN.toml [compile]`), for `gfx1151`. Nothing is loaded or run on the GPU.')
w('')
w('| origin | toolchain | compiler | modules passed | units passed | how a unit is defined |')
w('|---|---|---|---|---|---|')
how = {'strixfold': 'one `.hip` source to one raw `.hsaco` (`hipcc --offload-device-only`)',
       'gufo': 'one translation unit to one object (`clang++ -x hip -c`), per-source options from the origin\'s CMake',
       'hipfire': 'one source constant of `rdna-compute` (defines + sources concatenated) to one bundle (`hipcc --genco`)'}
tot_m = tot_p = tot_u = tot_up = 0
for og in ORIGINS:
    rs = [r for k, r in res.items() if k.split('.')[1] == og]
    if not rs:
        continue
    passed = sum(1 for r in rs if r['status'] == 'pass')
    units, up = sum(r['units'] for r in rs), sum(r['passed'] for r in rs)
    tot_m += len(rs); tot_p += passed; tot_u += units; tot_up += up
    w(f"| {og} | {rs[0]['toolchain']} (`{rs[0]['toolchain_root']}`) | {rs[0]['compiler'].replace(' | ', '; ')[:95]} | {passed} of {len(rs)} | {up} of {units} | {how[og]} |")
w(f'| total | | | {tot_p} of {tot_m} | {tot_up} of {tot_u} | |')
w('')
w('Kernel modules that are not compiled standalone, and why:')
w('')
w('| module | `[gate].compile` | reason |')
w('|---|---|---|')
for og in ORIGINS:
    for m in mods[og]:
        g = m['gate']
        if m['kind'] == 'kernel' and g.get('compile') != 'standalone':
            w(f"| `{m['id']}` | {g.get('compile')} | {g.get('reason', '')} |")
w('')
fails = [r for r in res.values() if r['status'] != 'pass' and r['module'].split('.')[1] in ORIGINS]
if fails:
    w('Failures:')
    w('')
    for r in fails:
        w(f"- `{r['module']}`: {r.get('reason', '')}")
    w('')
ex_path = os.path.join(REPO, 'docs/harvest/data/hipfire/not_gfx1151.json')
if os.path.exists(ex_path):
    ex = json.load(open(ex_path))
    c = collections.Counter(v['class'] for v in ex.values())
    w(f'hipfire units that are **not** in the gate ({len(ex)}; `docs/harvest/data/hipfire/not_gfx1151.json` has each one with the compiler\'s message).')
    w('They failed the first gate run (with `/opt/rocm-7.2.4`), for these causes, and were then taken out of `units.json`; they were not tried again with TheRock 10.2:')
    w('')
    why = {'arch': 'not gfx1151 material: the source has `#error` for anything but gfx1201 (FP8 E4M3 KV and attention, one hyper-connection kernel), uses `__builtin_amdgcn_sdot4` (dot1-insts, absent on gfx1151), or is a ggml shim shipped only as a gfx1201 object. Sources used by no other unit were dropped from the harvest.',
           'origin-broken': 'the origin\'s own unit calls `fwht_shfl_forward_512`, which no file in the tree at efa8fbb defines (`turbo_common.h` has the 128 and 256 forms); the only launcher of these four is `gemma4_ext.rs`, a left-out family. The sources stay in `src/` without a unit.'}
    for k, n in c.most_common():
        w(f'- {n} `{k}`: {why.get(k, "")}')
    w('')
    oc = load(os.path.join(REPO, 'catalog/hipfire/ORIGIN.toml'))['kernels']
    w(f"hipfire source accounting: {oc['sources_total']} `.hip` files under `kernels/src`; {oc['sources_other_arch']} named for another architecture,")
    w(f"{oc['sources_left_out_non_llm']} image / audio / bench sources, {oc['sources_dropped_not_gfx1151']} dropped as not gfx1151 (above); of the rest, {oc['sources_without_unit']} have no compile unit.")
    w(f"Of {oc['registry_constants']} source constants, {oc['gate_units']} are gfx1151 gate units; skipped: " + '; '.join(oc['units_skipped']) + '.')
    w('')
w('Prebuilt code objects (recorded with hashes, never rebuilt here):')
w('')
for og in ORIGINS:
    for m in mods[og]:
        for pb in m.get('prebuilt', [])[:1]:
            n = len(m.get('prebuilt', []))
            w(f"- `{m['id']}`: {n} `[[prebuilt]]` record(s). {m['gate'].get('reason', '')}")
w('')
w('What the gate does not show: that a kernel computes the right thing, or how fast. Objects are deleted after hashing.')
w('')
w('### The kit hashes')
w('')
w('The strixfold objects of this gate have the same byte sizes as the ones the origin\'s `zig build` produced on control-node, but different hashes.')
w('Cause (found in phase 3, reproduced both ways on control-node with TheRock 10.2): clang gives every HIP translation unit a compile unit id,')
w('the symbol `__hip_cuid_<hash>`, and derives it from the **strings of its command line**, the input path and the `-o` path among them. The')
w('hex digits of that symbol name, and with them the order of the dynamic symbol and hash tables, are the only bytes that differ (186 bytes in')
w('`glue.hsaco`). Nothing else enters: no timestamp, no absolute path (the same relative command gives the same bytes in any directory).')
w('`zig build` passes the paths relative to the build root (`./zig/kernels/hip/dsv41/glue.hip`, `-I./zig/kernels/hip/dsv41`) but names the output')
w('`./.zig-cache/o/<digest>/glue.hsaco`, and that digest covers the absolute paths of the step\'s inputs, so it changes with the location of the')
w('checkout. Hence: workers F and A (same home path) build identical kits; control-node\'s `fork` and its worktree `af9276f296/wt` do not; and')
w('this gate\'s own command line (other `-I` and `-o`) gives a third set.')
w('')
w('The recipe `dsv41-flash.strixfold-tp2` reproduces the reference deployment\'s kit byte for byte: `[build.hipcc_output_pins]` records the cache')
w('directory name the reference build (the worktree the deployment on F and A was built in) compiled each object into,')
w('and `flerp assemble` routes hipcc through a wrapper that compiles to that path string and copies the object to where Zig asked. Result on')
w('control-node: 169 objects and the deployment\'s kit manifest sha256, at each commit cut so far: f44d736 (deployment f44d73633ef5, built in')
w('`af9276f296/wt`, `2776d4b8...72cc`), then ef4c5f7 and f64b5ff (deployments ef4c5f726f54 and f64b5ff2e28b, built in `d74bd09137/wt`, `76936479...8455`).')
w('')
w('### Re-cutting StrixFold to the commit the pod serves')
w('')
w('The serving build on F and A moves with the pod\'s own StrixFold work. One command re-cuts the catalogue, the kit pins and the gate\'s reference:')
w('')
w('```')
w('python3 gate/strixfold_recut.py <commit> <deploy-dir-name>      # e.g. f64b5ff f64b5ff2e28b; run on the laptop, re-runnable')
w('tools/pod-sync.sh')
w("tools/pod-run.sh './flerp gate recipe dsv41-flash.strixfold-tp2 --stages check,origin,build'")
w("tools/pod-run.sh './flerp assemble dsv41-flash.strixfold-tp2-abi && build/dsv41-flash.strixfold-tp2-abi/build.sh'")
w('```')
w('')
w('It exports the commit from the pod fork (`git archive`), checks that `~/tfp/deploy/<deploy-dir-name>` on worker A is that commit, finds the')
w('worktree whose build is the deployed kit and reads the pins from its Zig cache, re-runs `docs/harvest/harvest_strixfold.py` on the export and')
w('rewrites the pins and the reference in the two recipes, `gate/dsv41-flash.strixfold-tp2.toml` and the gate\'s base conf. It refuses when the')
w('deployment is another commit or no worktree still holds its build. It reads the pair (ssh, read-only) and does not commit.')
w('The four binaries are not byte-identical to the deployed ones: they carry the absolute path of the build tree (5 occurrences in `tensorfold-native`).')
w('')
w('## Left out, and why')
w('')
for og in ORIGINS:
    hv = json.load(open(os.path.join(REPO, 'catalog', og, 'HARVEST.json')))
    w(f'### {og}')
    w('')
    w('| origin paths | why |')
    w('|---|---|')
    for k, v in hv.get('left_out', {}).items():
        v = v if len(v) < 900 else v[:900] + ' ...'
        w(f'| `{k}` | {v} |')
    w('')
w('### sglang, halogen')
w('')
for og in ('sglang', 'halogen'):
    oc = load(os.path.join(REPO, 'catalog', og, 'ORIGIN.toml'))
    w(f"- **{og}**: {oc['harvest_reason']}")
w('')
w('## Not verified')
w('')
w('- No module was run on a GPU. `gate.status` is `builds` at most.')
w('- hipfire\'s Rust modules were not compiled: they build only inside a recipe. Of gufo\'s C++ host, the Qwen 3.5 text executor and what it')
w('  links build in the recipe `qwen35-decider-2b.gufo` (phase 5, 131 files, `gate/results/qwen35-decider-2b.gufo/compiled-files.json`); the')
w('  Flash-Next and DeepSeek engines, the TP2 transport and the server were not compiled. StrixFold\'s Zig modules build in the')
w('  recipe `dsv41-flash.strixfold-tp2` (phase 3, `gate/results/dsv41-flash.strixfold-tp2/`); they have not run on a GPU from that build.')
w('- The StrixFold serving kit on workers F and A (169 objects, 302 kernels) was not read; its figures come from `/data/pod/plans/strixfold/PATHS.md`.')
w('  The Triton kit hashes were taken from the copy on control-node (`/data/pod/plans/af9276f296/tri-kit-gfx1151`, 158 objects).')
w('- gufo: 21 quoted `#include` lines in `serve.gufo.http` and `runtime.gufo.ext_api` name headers of the left-out audio, video,')
w('  embedding and CLI code (`flerp check -w`). Those modules need the headers or stubs before they build. The Qwen vision input and the')
w('  image helpers were left out too until phase 5 needed them: `executor.gufo.qwen` does not build without `executor.gufo.qwen_vision`')
w('  and `runtime.gufo.image` (recipe `qwen35-decider-2b.gufo`).')
w('- sglang and halogen entries were written from directory listings on control-node; nothing was built or run.')
w('- Interface names, numeric contracts and regimes in the manifests were written from header comments and launch signatures.')
open(os.path.join(REPO, 'docs', 'HARVEST.md'), 'w').write('\n'.join(o) + '\n')
print('docs/HARVEST.md', len(o), 'lines')
