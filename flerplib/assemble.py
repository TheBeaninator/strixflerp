"""`flerp assemble`: a recipe -> a CMake + Ninja source tree that compiles exactly the recipe's modules.

The generated CMakeLists.txt names catalogue files only. Flags and toolchain handling follow strixite's own
CMakeLists.txt (catalog/strixite/ORIGIN.toml): TheRock's clang builds host and device code, .hip files are CXX
sources compiled with `-x hip --offload-arch=<arch> --rocm-path=<root>`, the host C++ stdlib comes from a GCC
install, Release is -O3 -march=<host> -flto linked with lld.

Each module with sources becomes one OBJECT library, compiled once with the include directories of itself and of
its transitive requirements only, so a header a module did not declare in `requires` is not found. A binary links
its entry module plus the objects of that module's closure.

Three things make a cross-engine assembly (SPEC.md section 5):
- A module whose origin has its own compile recipe (ORIGIN.toml [compile]) is compiled by that recipe, command for
  command, not by the flags above. A recipe that yields host objects (gufo: clang++ -x hip) becomes a static
  library the binaries link; one that yields device code objects (StrixFold: hipcc --offload-device-only, hipfire:
  hipcc --genco) compiles only the units an adapter names, and each is embedded in the binary as bytes between
  the symbols <symbol> and <symbol>_end.
- An adapter ([adapter] for / symbols) takes over launch functions of a module: that module's translation units
  are compiled with -D<symbol>=<symbol>_flerp_origin, so the adapter defines the name the callers use and the
  original stays reachable. No vendored file changes.
- Both are recorded in assembly.json.
"""
