def header_text(cat, toolchain, label, out_dir):
    tc = cat.toolchains.get(toolchain, {})
    sub = {"RECIPE": label, "TOOLCHAIN": toolchain, "ROOT_REL": os.path.relpath(cat.root, out_dir),
           "ROCM_ROOT": tc.get("rocm_root", ""), "CC": tc.get("cc", "lib/llvm/bin/clang"),
           "CXX": tc.get("cxx", "lib/llvm/bin/clang++"), "ARCH": tc.get("arch", "gfx1151"),
           "HOST_MARCH": tc.get("host_march", "znver5")}
    return re.sub(r"@([A-Z_]+)@", lambda m: sub[m.group(1)], HEADER)


def rename_defines(symbols):
    return [f"{s}={s}{RENAME_SUFFIX}" for s in symbols]


def cm_quote(arg, root=None):
    """A CMake string argument; a path under the repository root is written from ${FLERP_ROOT}."""
    q = arg.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$")
    if root and arg.startswith(root + "/"):
        q = "${FLERP_ROOT}" + q[len(root):]
    return '"' + q + '"'


def foreign_command(cat, m, deps, cr, source, out, extra_flags=(), renames=()):
    """The origin's compile command for one source of module m, as a list of arguments (absolute paths)."""
    incs = [d for c in [m] + list(deps) for d in c.include_dirs] + cr["system_includes"]
    incs = list(dict.fromkeys(incs))
    return ([cr["driver"]] + [b for b in cr["base"] if b] + cr["flags"] + list(extra_flags)
            + ["-D" + d for d in rename_defines(renames)] + [x for i in incs for x in ("-I", i)]
            + cr["source_prefix"] + [source, "-o", out])


def emit_foreign(cat, m, deps, cr, lines, record, renames=()):
    """A module built by its origin's host-object compile recipe: one custom command per source, exactly the
    origin's command, and a static library of the objects (so a binary links only the objects it needs)."""
    t = target(m.id)
    objs = []
    lines.append(f"\n# {m.id}: {m.summary}\n# built by the compile recipe of origin {m.dir_origin} "
                 f"(catalog/{m.dir_origin}/ORIGIN.toml [compile], toolchain {cr['toolchain']})")
    record["commands"] = []
    for i, s in enumerate(m.sources):
        src = os.path.join(m.dir, s)
        out = f"${{CMAKE_BINARY_DIR}}/foreign/{m.id}/{i}-{os.path.basename(s)}.o"
        cmd = foreign_command(cat, m, deps, cr, src, "@OUT@", m.build.get("source_options", {}).get(s, []), renames)
        record["commands"].append(" ".join(shlex.quote(c) for c in cmd).replace(cat.root + "/", ""))
        args = " ".join(out if c == "@OUT@" else cm_quote(c, cat.root) for c in cmd)
        lines.append(f"add_custom_command(OUTPUT {out}\n    COMMAND ${{CMAKE_COMMAND}} -E make_directory "
                     f"${{CMAKE_BINARY_DIR}}/foreign/{m.id}\n    COMMAND {args}\n    DEPENDS {cm_quote(src, cat.root)}\n"
                     f"    COMMENT \"{m.dir_origin} compile recipe: {os.path.basename(s)}\" VERBATIM)")
        objs.append(out)
    lines.append(f"set_source_files_properties({cm_list(objs)}\n    PROPERTIES EXTERNAL_OBJECT TRUE GENERATED TRUE)")
    lines.append(f"add_library({t} STATIC{cm_list(objs)})")
    lines.append(f"set_target_properties({t} PROPERTIES LINKER_LANGUAGE CXX)")


def emit_code_object(cat, asm, adapter, co, out_dir, lines, record):
    """One device code object an adapter loads: compiled by its module's origin recipe, then embedded as bytes
    between <symbol> and <symbol>_end. Returns the object file to link."""
    src_mod = cat.by_id[co["module"]]
    cr = cat.compile_recipe(src_mod)
    unit = src_mod.units()[co["unit"]]
    sym = co["symbol"]
    if "parts" in unit:      # a unit of concatenated text: written into the build tree, parts in order
        os.makedirs(os.path.join(out_dir, "units"), exist_ok=True)
        gen = os.path.join(out_dir, "units", sym + ".hip")
        origin_dir = os.path.join(cat.root, "catalog", src_mod.dir_origin)
        with open(gen, "w") as f:
            for part in unit["parts"]:
                if "text" in part:
                    f.write(part["text"])
                else:
                    with open(os.path.join(origin_dir, part["path"]), errors="replace") as g:
                        f.write(g.read())
        source = dep = "${CMAKE_CURRENT_LIST_DIR}/units/" + sym + ".hip"
    else:
        source = dep = cm_quote(os.path.join(src_mod.dir, unit["source"]), cat.root)
    deps = [cat.by_id[d] for d in asm.deps(src_mod.id)]
    cmd = foreign_command(cat, src_mod, deps, cr, "@SRC@", "@OUT@", unit.get("flags", []))
    hsaco = f"${{CMAKE_BINARY_DIR}}/co/{sym}.hsaco"
    record.append({"adapter": adapter.id, "module": src_mod.id, "unit": co["unit"], "symbol": sym,
                   "toolchain": cr["toolchain"],
                   "command": " ".join(shlex.quote(c) for c in cmd).replace(cat.root + "/", "")})
    args = " ".join(hsaco if c == "@OUT@" else source if c == "@SRC@" else cm_quote(c, cat.root) for c in cmd)
    asm_file = f"${{CMAKE_BINARY_DIR}}/co/{sym}.S"
    obj = f"${{CMAKE_BINARY_DIR}}/co/{sym}.o"
    lines.append(f"\n# code object {sym}: unit {co['unit']} of {src_mod.id}, built by the compile recipe of origin "
                 f"{src_mod.dir_origin}, loaded by {adapter.id}")
    lines.append("file(MAKE_DIRECTORY ${CMAKE_BINARY_DIR}/co)")
    lines.append(f"file(WRITE {asm_file} \"    .section .rodata\\n    .global {sym}\\n    .global {sym}_end\\n"
                 f"    .balign 64\\n{sym}:\\n    .incbin \\\"${{CMAKE_BINARY_DIR}}/co/{sym}.hsaco\\\"\\n{sym}_end:\\n"
                 f"    .byte 0\\n    .section .note.GNU-stack,\\\"\\\",@progbits\\n\")")
    lines.append(f"add_custom_command(OUTPUT {hsaco}\n    COMMAND {args}\n    DEPENDS {dep}\n"
                 f"    COMMENT \"{src_mod.dir_origin} compile recipe: {co['unit']}\" VERBATIM)")
    lines.append(f"add_custom_command(OUTPUT {obj}\n    COMMAND ${{CMAKE_C_COMPILER}} -c {asm_file} -o {obj}\n"
                 f"    DEPENDS {hsaco}\n    COMMENT \"embed code object {sym}\" VERBATIM)")
    lines.append(f"set_source_files_properties({obj} PROPERTIES EXTERNAL_OBJECT TRUE GENERATED TRUE)")
    return obj


def overlay_sources(cat, origin, derived):
    """The sources of `origin`'s target under a recipe's [overlay] by `derived`: each derived source at
    src/<derived include root>/<path> replaces the origin's src/<path>. Returns (absolute paths, errors)."""
    errors, swap = [], {}
    roots = [os.path.relpath(d, os.path.join(derived.dir, "src")) for d in derived.include_dirs]
    for s in derived.sources:
        rel = os.path.relpath(os.path.join(derived.dir, s), os.path.join(derived.dir, "src"))
        root = next((r for r in roots if rel.startswith(r + os.sep)), None)
        want = "src/" + os.path.relpath(rel, root) if root else None
        if want not in origin.sources:
            errors.append(f"[overlay] {derived.id}: source {s} replaces no source of {origin.id}")
        else:
            swap[want] = os.path.join(derived.dir, s)
    return [swap.get(s, os.path.join(origin.dir, s)) for s in origin.sources], errors


def emit_module(cat, m, deps, lines, extra_sources=(), renames=(), overlays=None):
    """Appends the OBJECT library of one module (if it has sources). deps: its transitive requirements.
    renames: symbols an adapter takes over from this module. overlays: origin module id -> derived Module (a
    recipe's [overlay]): an overlaid module compiles the derived sources, and the derived include roots go ahead of
    the origin's on every include path. Returns whether its compile line carries the HIP runtime."""
    overlays = overlays or {}
    chain = [m] + sorted(deps, key=lambda d: d.id)
    hip_rt = any("hip-runtime" in c.build.get("uses", []) for c in chain)
    if m.id in overlays:
        sources = overlay_sources(cat, m, overlays[m.id])[0] + list(extra_sources)
    else:
        sources = [os.path.join(m.dir, s) for s in m.sources] + list(extra_sources)
    if not sources:
        return hip_rt

    def rooted(path):
        return "${FLERP_ROOT}/" + os.path.relpath(path, cat.root)

    t = target(m.id)
    hip = [s for s in sources if s.endswith((".hip", ".cu"))]   # .cu is hip-c++ when the module says so (catalog.COMPILED)
    lines.append(f"\n# {m.id}: {m.summary}")
    lines.append(f"add_library({t} OBJECT{cm_list(rooted(s) for s in sources)})")
    if hip:
        lines.append(f"set_source_files_properties({cm_list(rooted(s) for s in hip)}\n"
                     f"    PROPERTIES LANGUAGE CXX COMPILE_OPTIONS \"${{FLERP_HIP_OPTIONS}}\")")
    def dirs(c):
        return (overlays[c.id].include_dirs if c.id in overlays else []) + c.include_dirs

    normal = [rooted(d) for c in chain if not c.build.get("system") for d in dirs(c)]
    system = [rooted(d) for c in chain if c.build.get("system") for d in c.include_dirs]
    if hip_rt:
        system.append("${FLERP_ROCM_ROOT}/include")
    if normal:
        lines.append(f"target_include_directories({t} PRIVATE{cm_list(normal)})")
    if system:
        lines.append(f"target_include_directories({t} SYSTEM PRIVATE{cm_list(system)})")
    defines = (["__HIP_PLATFORM_AMD__"] if hip_rt else []) + m.build.get("defines", []) + rename_defines(renames)
    if defines:
        lines.append(f"target_compile_definitions({t} PRIVATE {' '.join(defines)})")
    if m.build.get("options"):
        lines.append(f"target_compile_options({t} PRIVATE {' '.join(m.build['options'])})")
    if m.lang == "c" and m.build.get("c_std"):
        lines.append(f"set_target_properties({t} PROPERTIES C_STANDARD {m.build['c_std']} C_EXTENSIONS OFF)")
    return hip_rt


def generate(cat, recipe, out_dir, licence=None):
    """Writes out_dir/CMakeLists.txt and out_dir/assembly.json. Returns (assembly, errors)."""
    from . import assemble_cmake, assemble_zig
    if assemble_zig.is_zig(recipe):            # a Zig-hosted recipe ([build] system = "zig") is a source tree
        return assemble_zig.generate(cat, recipe, out_dir, licence)
    if assemble_cmake.is_cmake(recipe):        # so is one built by its origin's CMake files ([build] system = "cmake")
        return assemble_cmake.generate(cat, recipe, out_dir, licence)
    from . import assemble_make
    if assemble_make.is_make(recipe):          # and one built by its origin's Makefile ([build] system = "make")
        return assemble_make.generate(cat, recipe, out_dir, licence)
    asm = Assembly(cat, recipe)
    errors = list(asm.errors)
    if not isinstance(cat.toolchains.get(recipe.toolchain), dict):
        errors.append(f"toolchain '{recipe.toolchain}' is not in toolchains.toml")
    for mid in asm.modules:
        m = cat.by_id[mid]
        if m.sources and m.lang not in COMPILED:
            errors.append(f"{mid}: lang {m.lang} cannot be assembled yet")
        if licence and not licence_matches(m.spdx, licence):
            errors.append(f"{mid}: licence '{m.spdx}' is outside --licence {licence}")
        cr = cat.compile_recipe(m)
        if cr is not None and not isinstance(cat.toolchains.get(cr["toolchain"]), dict):
            errors.append(f"{mid}: [build] toolchain '{cr['toolchain']}' is not in toolchains.toml")
        if cr is not None and cr["product"] == "code-object" and asm.renames.get(mid):
            errors.append(f"{mid}: a module of device code objects has no host symbols an adapter could take over")
        if mid in asm.overlays:
            errors += overlay_sources(cat, m, cat.by_id[asm.overlays[mid]])[1]
        for co in m.code_objects:
            src = cat.by_id.get(co.get("module"))
            if (src is None or co.get("unit") not in src.units()
                    or (cat.compile_recipe(src) or {}).get("product") != "code-object"):
                errors.append(f"{mid}: [[adapter.code_object]] {co.get('module')} / {co.get('unit')} cannot be built "
                              "(see flerp check)")
    if errors:
        return asm, errors

    out_dir = os.path.abspath(out_dir)
    lines = [header_text(cat, recipe.toolchain, recipe.name, out_dir),
             "# --- modules: one OBJECT library per module with sources " + "-" * 53]
    uses_hip, foreign, code_objects, embedded = {}, {}, [], {}
    overlays = {oid: cat.by_id[did] for oid, did in asm.overlays.items()}
    derived = set(asm.overlays.values())
    for mid in asm.modules:
        m, deps = cat.by_id[mid], [cat.by_id[d] for d in asm.deps(mid)]
        cr = cat.compile_recipe(m)
        renames = asm.renames.get(mid, [])
        if mid in derived:                     # compiled in the target of the module it overlays
            uses_hip[mid] = False
            continue
        if cr is None:
            uses_hip[mid] = emit_module(cat, m, deps, lines, renames=renames, overlays=overlays)
        else:
            uses_hip[mid] = True
            foreign[mid] = {"origin": m.dir_origin, "product": cr["product"], "toolchain": cr["toolchain"]}
            if cr["product"] == "host-object" and m.sources:
                emit_foreign(cat, m, deps, cr, lines, foreign[mid], renames)
        embedded[mid] = [emit_code_object(cat, asm, m, co, out_dir, lines, code_objects) for co in m.code_objects]

    def compiled_here(i):      # modules whose objects go straight into a binary
        return bool(cat.by_id[i].sources) and i not in foreign and i not in derived

    lines.append("\n# --- binaries: the entry module's objects plus its closure's " + "-" * 50)
    linked = set()
    manifest = {"recipe": recipe.name, "toolchain": recipe.toolchain, "binaries": {}, "modules": {}}
    for name, (main, entry, ids) in asm.binaries.items():
        objs = [i for i in ids if compiled_here(i)]
        linked.update(objs)
        linked.update(i for i in ids if i in foreign)
        extra = [o for i in ids for o in embedded.get(i, [])]
        lines.append(f"\nadd_executable({name}{cm_list([f'$<TARGET_OBJECTS:{target(i)}>' for i in objs] + extra)})")
        lines.append(f"set_target_properties({name} PROPERTIES LINKER_LANGUAGE CXX)")
        # static libraries of modules built by another origin's recipe: the linker takes the objects it needs
        libs = [target(i) for i in ids if foreign.get(i, {}).get("product") == "host-object" and cat.by_id[i].sources]
        libs.append("Threads::Threads")
        if uses_hip[main]:
            libs.append("${FLERP_HIP_LIB}")
            lines.append(f"target_link_options({name} PRIVATE \"-Wl,-rpath,${{FLERP_ROCM_ROOT}}/lib\")")
        lines.append(f"target_link_libraries({name} PRIVATE {' '.join(libs)})")
        manifest["binaries"][name] = {"main": main, "entry": entry, "modules": ids}
    rest = [i for i in asm.modules if compiled_here(i) and i not in linked]
    if rest:
        lines.append("\n# [include] modules no binary links: compiled so the build proves them.")
        lines.append(f"add_library(flerp_include_only STATIC{cm_list(f'$<TARGET_OBJECTS:{target(i)}>' for i in rest)})")
        lines.append("set_target_properties(flerp_include_only PROPERTIES LINKER_LANGUAGE CXX)")
    for mid in asm.modules:
        m = cat.by_id[mid]
        manifest["modules"][mid] = {"dir": cat.rel(m.dir), "spdx": m.spdx, "sources": m.sources,
                                    "files": len(m.files()), "linked": mid in linked or not m.sources}
    manifest["bindings"] = dict(recipe.bindings)
    manifest["include_only"] = rest
    manifest["foreign"] = foreign                # modules built by their origin's compile recipe
    manifest["code_objects"] = code_objects      # device code objects embedded for adapters
    manifest["renames"] = {mid: {"adapter": asm.adapters[mid], "symbols": syms, "suffix": RENAME_SUFFIX}
                           for mid, syms in asm.renames.items()}
    manifest["overlays"] = {did: {"origin": oid, "sources": [cat.rel(p) for p in
                                                             overlay_sources(cat, cat.by_id[oid], cat.by_id[did])[0]]}
                            for oid, did in asm.overlays.items()}
    manifest["contract_changes"] = [{"required": i, "provided": p, "module": d} for i, p, d in asm.contract_changes]

    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "CMakeLists.txt"), "w") as f:
        f.write("\n".join(lines) + "\n")
    with open(os.path.join(out_dir, "assembly.json"), "w") as f:
        json.dump(manifest, f, indent=1, sort_keys=True)
        f.write("\n")
    return asm, []


def generate_module(cat, module, out_dir, bindings=None):
    """A tree that compiles one module on its own (the module gate). A header-only module gets one generated
    translation unit that includes each of its headers. Returns errors."""
    errors = []
    deps = [cat.by_id[i] for i in closure(cat, [module.id], bindings, errors) if i != module.id]
    toolchain = module.build.get("toolchain")
    if not isinstance(cat.toolchains.get(toolchain), dict):
        errors.append(f"{module.id}: [build] toolchain '{toolchain}' is not in toolchains.toml")
    if module.sources and module.lang not in COMPILED:
        errors.append(f"{module.id}: lang {module.lang} cannot be compiled by this gate yet")
    if errors:
        return errors
    out_dir = os.path.abspath(out_dir)
    os.makedirs(out_dir, exist_ok=True)
    extra = []
    if not module.sources:
        hip_rt = any("hip-runtime" in c.build.get("uses", []) for c in [module] + deps)
        probe = os.path.join(out_dir, "headers_probe.hip" if hip_rt else "headers_probe.cpp")
        heads = []
        for p in module.files():
            if p.endswith((".h", ".hpp")):
                full = os.path.join(module.dir, "src", p)
                rel = next((os.path.relpath(full, d) for d in module.include_dirs if full.startswith(d + os.sep)), None)
                if rel:
                    heads.append(rel)
        with open(probe, "w") as f:
            f.write("".join(f"#include <{h}>\n" for h in heads) + "int flerp_headers_probe() { return 0; }\n")
        extra = [probe]
    lines = [header_text(cat, toolchain, "module " + module.id, out_dir)]
    emit_module(cat, module, deps, lines, extra)
    with open(os.path.join(out_dir, "CMakeLists.txt"), "w") as f:
        f.write("\n".join(lines) + "\n")
    return []
