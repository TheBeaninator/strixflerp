"""`flerp assemble` for a recipe built by its origin's CMake build graph (`[build] system = "cmake"`).

gufo is C++ and HIP built by CMake: its targets, per-source options and link order are in CMake files that sit
next to the sources and are harvested with them. A recipe that takes an executor of such an origin whole is not a
list of compile units to re-describe in a generated CMakeLists.txt; it is a source tree those files build:

    build/<recipe>/tree/          every file of the recipe's module closure at its origin-relative path (copies,
                                  byte for byte; the catalogue is the only source)
    build/<recipe>/assembly.json  modules, the owner and sha256 of every tree file, the configure and build commands
    build/<recipe>/build.sh       checks the tree against assembly.json, configures and builds out/ with the
                                  toolchain of toolchains.toml, links strixflerp-<recipe>

The origin's root CMakeLists.txt is not in the catalogue when it builds more than the recipe (gufo's builds every
model family into one binary), so the top of the graph is a build file of a module of the assembly: a CMakeLists.txt
that declares what the root declares for the targets the recipe needs and adds the origin's directories unchanged.
A tree that lacks a file those CMake files name does not configure, which is the check that the closure is whole.

Recipe keys read here:

    [build]
    system     = "cmake"
    root       = "<module id>"               # the module that holds the build file; it must be in the assembly
    build_file = "flerp/gufo_qwen/CMakeLists.txt"   # its tree path; cmake -S is its directory
    targets    = ["flerp-gufo-qwen-generate"]       # ninja targets
    options    = ["-DNAME=value", ...]       # configure options; {rocm} = the toolchain's rocm_root
    headers    = ["include/flerp/executor.h"]   # optional: repository files copied into the tree at the same path
    [build.installs]                         # binary name in [binaries] -> path under build/<recipe>/out
"""
import json
import os
import re
import shutil

from .assemble_zig import sha256

SYSTEM = "cmake"
BUILD_KEYS = {"system": str, "root": str, "build_file": str, "targets": list, "options": list, "installs": dict,
              "headers": list}
REQUIRED = ("root", "build_file", "targets")


def is_cmake(recipe):
    b = recipe.data.get("build")
    return isinstance(b, dict) and b.get("system") == SYSTEM


def handles(recipe, module):
    """True when this assembler builds `module`'s sources for `recipe` (the hook `flerp check` asks): the origin's
    CMake files compile them, with the origin's own flags."""
    return is_cmake(recipe) and module.lang in ("hip-c++", "c", "c++")


def plan(cat, recipe, asm):
    """The tree as {tree path: (module id, absolute source)} plus errors. Nothing is written."""
    errors, tree = [], {}
    for mid in asm.modules:
        m = cat.by_id[mid]
        for rel in m.files():
            if rel in tree:
                errors.append(f"{rel}: in both {tree[rel][0]} and {mid}")
            tree[rel] = (mid, os.path.join(m.dir, "src", rel))
    build = recipe.data.get("build", {})
    for rel in build.get("headers", []):
        src = os.path.join(cat.root, rel)
        if not os.path.isfile(src):
            errors.append(f"[build] headers: {rel} is not a file of the repository")
        elif rel in tree:
            errors.append(f"[build] headers: {rel} is also a file of {tree[rel][0]}")
        else:
            tree[rel] = ("-", src)
    root = build.get("root")
    if root not in asm.modules:
        errors.append(f"[build] root {root} is not a module of the assembly")
    build_file = build.get("build_file")
    if build_file not in tree:
        errors.append(f"build file {build_file} is in no module of the assembly")
    elif tree[build_file][0] != root:
        errors.append(f"build file {build_file} belongs to {tree[build_file][0]}, not to [build] root {root}")
    for name in asm.binaries:
        if name not in build.get("installs", {}):
            errors.append(f"[build.installs] has no entry for binary {name}")
    return tree, errors


def configure_options(cat, recipe):
    rocm = cat.toolchains.get(recipe.toolchain, {}).get("rocm_root", "")
    opts = [re.sub(r"\{rocm\}", "${FLERP_ROCM_ROOT}", o) for o in recipe.data.get("build", {}).get("options", [])]
    return opts, rocm


BUILD_SH = r'''#!/bin/bash
# Generated by `flerp assemble @RECIPE@`. Do not edit: change the recipe or a module manifest and assemble again.
# Builds tree/ with the origin's own CMake files. Usage: build.sh [-jN] [extra cmake configure arguments]
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$here/@ROOT_REL@" && pwd)
export FLERP_ROCM_ROOT=${FLERP_ROCM_ROOT:-@ROCM@}
jobs=-j${FLERP_JOBS:-4}
case "${1:-}" in -j*) jobs=$1; shift;; esac
[ -x "$FLERP_ROCM_ROOT/lib/llvm/bin/clang++" ] || { echo "build.sh: no clang++ under $FLERP_ROCM_ROOT (set FLERP_ROCM_ROOT)" >&2; exit 2; }
# the tree must still be what `flerp assemble` wrote from the catalogue
python3 "$root/flerplib/assemble_zig.py" verify-tree "$here"
# nice 19: the build host serves other work
nice -n 19 cmake -G Ninja -S "$here/tree/@SOURCE_DIR@" -B "$here/out" @OPTIONS@ "$@"
nice -n 19 ninja -C "$here/out" "$jobs" @TARGETS@
@LINKS@
'''


def generate(cat, recipe, out_dir, licence=None):
    """Writes out_dir/{tree/, assembly.json, build.sh}. Returns (assembly, errors) like assemble.generate."""
    from .catalog import licence_matches
    from .resolve import Assembly
    asm = Assembly(cat, recipe)
    errors = list(asm.errors)
    build = recipe.data.get("build", {})
    if not isinstance(cat.toolchains.get(recipe.toolchain), dict):
        errors.append(f"toolchain '{recipe.toolchain}' is not in toolchains.toml")
    for key in REQUIRED:
        if not isinstance(build.get(key), BUILD_KEYS[key]) or not build.get(key):
            errors.append(f"[build] {key} is missing or not a non-empty {BUILD_KEYS[key].__name__}")
    for mid in asm.modules:
        m = cat.by_id[mid]
        if m.sources and not handles(recipe, m):
            errors.append(f"{mid}: lang {m.lang} cannot be assembled by the cmake assembler")
        if licence and not licence_matches(m.spdx, licence):
            errors.append(f"{mid}: licence '{m.spdx}' is outside --licence {licence}")
    if errors:
        return asm, errors
    tree, perrors = plan(cat, recipe, asm)
    if perrors:
        return asm, perrors

    out_dir = os.path.abspath(out_dir)
    tdir = os.path.join(out_dir, "tree")
    os.makedirs(tdir, exist_ok=True)
    for d, _, names in os.walk(tdir):
        for n in names:
            if os.path.relpath(os.path.join(d, n), tdir) not in tree:
                os.remove(os.path.join(d, n))        # a file of an earlier assembly that is no longer in the closure
    files = {}
    for rel, (mid, src) in sorted(tree.items()):
        dst = os.path.join(tdir, rel)
        digest = sha256(src)
        files[rel] = {"module": mid, "sha256": digest}
        if os.path.isfile(dst) and sha256(dst) == digest:
            continue                                 # unchanged: keep its mtime so ninja rebuilds nothing
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copyfile(src, dst)
        shutil.copymode(src, dst)

    options, rocm = configure_options(cat, recipe)
    installs = build["installs"]
    source_dir = os.path.dirname(build["build_file"])
    links = [f'ln -sfn "out/{installs[name]}" "$here/{name}"' for name in asm.binaries]
    sub = {"RECIPE": recipe.name, "ROOT_REL": os.path.relpath(cat.root, out_dir), "ROCM": rocm,
           "SOURCE_DIR": source_dir, "OPTIONS": " ".join(f'"{o}"' for o in options),
           "TARGETS": " ".join(build["targets"]), "LINKS": "\n".join(links)}
    with open(os.path.join(out_dir, "build.sh"), "w") as f:
        f.write(re.sub(r"@([A-Z_]+)@", lambda m: sub[m.group(1)], BUILD_SH))
    os.chmod(os.path.join(out_dir, "build.sh"), 0o755)
    manifest = {"recipe": recipe.name, "system": SYSTEM, "toolchain": recipe.toolchain,
                "source_dir": source_dir, "configure_options": options, "targets": build["targets"],
                "bindings": dict(recipe.bindings),
                "binaries": {n: {"main": main, "entry": entry, "modules": ids, "installed": installs[n]}
                             for n, (main, entry, ids) in asm.binaries.items()},
                "modules": {mid: {"dir": cat.rel(cat.by_id[mid].dir), "spdx": cat.by_id[mid].spdx,
                                  "files": len(cat.by_id[mid].files())} for mid in asm.modules},
                "files": files}
    with open(os.path.join(out_dir, "assembly.json"), "w") as f:
        json.dump(manifest, f, indent=1, sort_keys=True)
        f.write("\n")
    print(f"cmake assembly: {len(files)} files -> {os.path.relpath(tdir)}; build: {os.path.relpath(out_dir)}/build.sh")
    return asm, []
