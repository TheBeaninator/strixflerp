"""`flerp assemble` for a recipe built by its origin's Makefile (`[build] system = "make"`).

Crucible is one HIP translation unit built by a Makefile: the assembly is the recipe's module closure copied to a
source tree at origin-relative paths (as for `system = "cmake"`, flerplib/assemble_cmake.py), and build.sh runs the
origin's own make target in it. The Makefile is a file of the module named by [build] root.

    [build]
    system     = "make"
    root       = "<module id>"            # holds the Makefile; it must be in the assembly
    build_file = "Makefile"               # its tree path; make runs in that file's directory
    targets    = ["build/engine/crucible.mono"]
    options    = ["NAME=value", ...]      # make variables; {rocm} = the toolchain's rocm_root
    [build.installs]                      # binary name in [binaries] -> path under tree/
"""
import json
import os
import re
import shutil

from . import assemble_cmake
from .assemble_zig import sha256

SYSTEM = "make"
BUILD_KEYS = {"system": str, "root": str, "build_file": str, "targets": list, "options": list, "installs": dict}
REQUIRED = ("root", "build_file", "targets")


def is_make(recipe):
    b = recipe.data.get("build")
    return isinstance(b, dict) and b.get("system") == SYSTEM


def handles(recipe, module):
    return is_make(recipe) and module.lang in ("hip-c++", "c", "c++")


BUILD_SH = r'''#!/bin/bash
# Generated by `flerp assemble @RECIPE@`. Do not edit: change the recipe or a module manifest and assemble again.
# Builds tree/ with the origin's own Makefile. Usage: build.sh [-jN] [extra make arguments]
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$here/@ROOT_REL@" && pwd)
export FLERP_ROCM_ROOT=${FLERP_ROCM_ROOT:-@ROCM@}
jobs=-j${FLERP_JOBS:-2}
case "${1:-}" in -j*) jobs=$1; shift;; esac
[ -x "$FLERP_ROCM_ROOT/bin/hipcc" ] || { echo "build.sh: no hipcc under $FLERP_ROCM_ROOT (set FLERP_ROCM_ROOT)" >&2; exit 2; }
# the tree must still be what `flerp assemble` wrote from the catalogue (make's outputs go to tree/build/, removed first)
rm -rf "$here/tree/build"
python3 "$root/flerplib/assemble_zig.py" verify-tree "$here"
cd "$here/tree/@SOURCE_DIR@"
env -u HIPCC_COMPILE_FLAGS_APPEND -u HIPCC_LINK_FLAGS_APPEND -u MAKEFLAGS \
    ionice -c3 nice -n 19 make "$jobs" @OPTIONS@ "$@" @TARGETS@
@LINKS@
'''


def generate(cat, recipe, out_dir, licence=None):
    from .catalog import licence_matches
    from .resolve import Assembly
    asm = Assembly(cat, recipe)
    errors = list(asm.errors)
    build = recipe.data.get("build", {})
    tc = cat.toolchains.get(recipe.toolchain)
    if not isinstance(tc, dict):
        errors.append(f"toolchain '{recipe.toolchain}' is not in toolchains.toml")
    for key in REQUIRED:
        if not isinstance(build.get(key), BUILD_KEYS[key]) or not build.get(key):
            errors.append(f"[build] {key} is missing or not a non-empty {BUILD_KEYS[key].__name__}")
    for mid in asm.modules:
        m = cat.by_id[mid]
        if m.sources and not handles(recipe, m):
            errors.append(f"{mid}: lang {m.lang} cannot be assembled by the make assembler")
        if licence and not licence_matches(m.spdx, licence):
            errors.append(f"{mid}: licence '{m.spdx}' is outside --licence {licence}")
    if errors:
        return asm, errors
    tree, perrors = assemble_cmake.plan(cat, recipe, asm)
    if perrors:
        return asm, perrors

    out_dir = os.path.abspath(out_dir)
    tdir = os.path.join(out_dir, "tree")
    os.makedirs(tdir, exist_ok=True)
    for d, _, names in os.walk(tdir):
        for n in names:
            if os.path.relpath(os.path.join(d, n), tdir) not in tree:
                os.remove(os.path.join(d, n))
    files = {}
    for rel, (mid, src) in sorted(tree.items()):
        dst = os.path.join(tdir, rel)
        digest = sha256(src)
        files[rel] = {"module": mid, "sha256": digest}
        if os.path.isfile(dst) and sha256(dst) == digest:
            continue
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copyfile(src, dst)
        shutil.copymode(src, dst)

    rocm = tc.get("rocm_root", "")
    options = [o.replace("{rocm}", "${FLERP_ROCM_ROOT}") for o in build.get("options", [])]
    installs = build.get("installs", {})
    source_dir = os.path.dirname(build["build_file"]) or "."
    links = [f'ln -sfn "tree/{installs[name]}" "$here/{name}"' for name in asm.binaries]
    sub = {"RECIPE": recipe.name, "ROOT_REL": os.path.relpath(cat.root, out_dir), "ROCM": rocm,
           "SOURCE_DIR": source_dir, "OPTIONS": " ".join(f'"{o}"' for o in options),
           "TARGETS": " ".join(build["targets"]), "LINKS": "\n".join(links)}
    with open(os.path.join(out_dir, "build.sh"), "w") as f:
        f.write(re.sub(r"@([A-Z_]+)@", lambda m: sub[m.group(1)], BUILD_SH))
    os.chmod(os.path.join(out_dir, "build.sh"), 0o755)
    manifest = {"recipe": recipe.name, "system": SYSTEM, "toolchain": recipe.toolchain, "source_dir": source_dir,
                "make_options": options, "targets": build["targets"], "bindings": dict(recipe.bindings),
                "binaries": {n: {"main": main, "entry": entry, "modules": ids, "installed": installs.get(n)}
                             for n, (main, entry, ids) in asm.binaries.items()},
                "modules": {mid: {"dir": cat.rel(cat.by_id[mid].dir), "spdx": cat.by_id[mid].spdx,
                                  "files": len(cat.by_id[mid].files())} for mid in asm.modules},
                "files": files}
    with open(os.path.join(out_dir, "assembly.json"), "w") as f:
        json.dump(manifest, f, indent=1, sort_keys=True)
        f.write("\n")
    print(f"make assembly: {len(files)} files -> {os.path.relpath(tdir)}; build: {os.path.relpath(out_dir)}/build.sh")
    return asm, []
