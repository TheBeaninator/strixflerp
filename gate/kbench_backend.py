"""Backend switch for the single-binary kernel microbench gates (DECODE-KERN3, ORNITH-KERN3, ATTN-PROJ).

    --backend kbench   (default) bench box K through pod-kbench k_run: no control-node GPU, no control-gpu lease, no
                       tools/gpu-queue.sh. The bench binary is still built on control-node (CPU, therock clang) exactly as
                       before; it is staged on K together with a generated run.sh that runs every case, one process a
                       case, and K's own loadavg / Tctl are read around each case.
    --backend queue    the old path on control-node's GPU (R1.run, control-node's loadavg).

The judges are unchanged: both backends write the same <tag>.jsonl / <tag>.err / <tag>-load.json (load_start/load_end
are the host's 1-min loadavg around each case's process, and the judge's "<= 6" test applies to whichever host ran it).
The kbench backend adds <tag>-method.json (host, job id, runtime, thermals) and per-case tctl_start/tctl_end to the
load rows. Method differences from the queue backend are recorded there and in each summary; no criterion is loosened.
"""
import json
import os
import re
import shlex
import shutil
import subprocess
import sys
import time

COOL_C = 50          # a case's process starts once K's Tctl <= this (as pod-kbench k_ab's cool_to_c), at most 90 s wait
LOAD_MAX = 6         # the criteria's loadavg limit
DEFAULT_CARD = os.environ.get("KB_CARD", "7a1a58e793")   # BENCH-K; the job dirs land under /data/pod/kbench/runs/<card>/
KLIB = "/opt/rocm/lib:/opt/rocm/lib/llvm/lib"

METHOD = {
    "kbench": ("bench box K (ltsp-k, gfx1151, balanced 85 W, quiet cooling, weak die contact), pod-kbench k_run, one lease "
               "for the whole stage, ROCm 7.2.4 runtime libs (the binary is built with therock 10.1 clang on control-node); "
               "each case's process starts at Tctl <= %d C (<= 90 s wait) and K's loadavg <= %d; the bench alternates "
               "ref/new rounds inside one process, so no ABBA process order is added" % (COOL_C, LOAD_MAX)),
    "queue": "control-node GPU (tools/gpu-queue.sh, lease control-gpu), therock HIP runtime, control-node loadavg <= %d" % LOAD_MAX,
}


def split_backend(argv):
    """(backend, remaining argv). --backend kbench|queue anywhere; GATE_BACKEND env; default kbench."""
    rest, backend, i = [], os.environ.get("GATE_BACKEND", "kbench"), 0
    while i < len(argv):
        a = argv[i]
        if a == "--backend" and i + 1 < len(argv):
            backend, i = argv[i + 1], i + 2
            continue
        if a.startswith("--backend="):
            backend, i = a.split("=", 1)[1], i + 1
            continue
        rest.append(a)
        i += 1
    if backend not in ("kbench", "queue"):
        sys.exit("--backend must be kbench or queue, got %r" % backend)
    return backend, rest


def results_dir(base, backend):
    """The queue backend keeps writing the committed control-node results; kbench writes beside them."""
    return base if backend == "queue" else os.path.join(base, "kbench")


def run_cases_k(root, res, tag, binary, cases, why, timeout_case=1500):
    """cases: [(name, argv after the binary)]. Returns the load rows (also written to <tag>-load.json)."""
    os.makedirs(res, exist_ok=True)
    out, err = os.path.join(res, tag + ".jsonl"), os.path.join(res, tag + ".err")
    stage = os.path.join(root, "build", "kbench", re.sub(r"[^A-Za-z0-9_.-]", "_", os.path.relpath(res, root) + "-" + tag))
    shutil.rmtree(stage, ignore_errors=True)
    os.makedirs(stage)
    shutil.copy2(os.path.join(root, binary), os.path.join(stage, "bench"))
    L = ["#!/usr/bin/env bash",
         "# generated by gate/kbench_backend.py; runs ON bench box K inside pod-kbench k_run",
         "export LD_LIBRARY_PATH=%s${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}" % KLIB,
         "TCTL=${KB_TCTL:-/sys/class/hwmon/hwmon2/temp1_input}",
         "tctl() { cat $TCTL 2>/dev/null || echo 0; }",
         ": > out.jsonl; : > err.txt; : > cases.tsv",
         "runcase() { name=$1; shift",
         "  for i in $(seq 60); do awk '{exit !($1 <= %d)}' /proc/loadavg && break; sleep 30; done" % LOAD_MAX,
         "  for i in $(seq 30); do [ \"$(tctl)\" -le %d ] && break; sleep 3; done" % (COOL_C * 1000),
         "  l0=$(cut -d' ' -f1 /proc/loadavg); t0=$(tctl)",
         "  timeout %d ./bench \"$@\" >> out.jsonl 2>> err.txt; rc=$?" % timeout_case,
         "  l1=$(cut -d' ' -f1 /proc/loadavg); t1=$(tctl)",
         "  printf '%s\\t%s\\t%s\\t%s\\t%s\\t%s\\n' \"$name\" $rc $l0 $l1 $t0 $t1 >> cases.tsv; }"]
    for name, args in cases:
        L.append("runcase %s %s" % (shlex.quote(name), " ".join(shlex.quote(a) for a in ["--case", name] + list(args))))
    open(os.path.join(stage, "run.sh"), "w").write("\n".join(L) + "\n")
    args = {"_card": DEFAULT_CARD, "_call": tag[-6:], "src": stage, "cmd": "bash ./run.sh",
            "fetch": ["out.jsonl", "err.txt", "cases.tsv"], "timeout_s": timeout_case * max(1, len(cases)),
            "why": why[:120]}
    argf = os.path.join(root, "build", "kbench", os.path.basename(stage) + ".args.json")
    json.dump(args, open(argf, "w"))
    p = subprocess.run(["pod-kbench", "k_run", "--args", argf], capture_output=True, text=True)
    sys.stderr.write(p.stdout[-3000:] + p.stderr[-1000:])
    m = re.search(r"k_run job (\S+) on bench box K \(([\d.]+)\).*files: (\S+)", p.stdout)
    if p.returncode != 0 or not m:
        raise SystemExit("pod-kbench k_run failed (rc %d)" % p.returncode)
    job, host, jd = m.groups()
    f = os.path.join(jd, "fetched")
    for src_, dst in (("out.jsonl", out), ("err.txt", err)):
        shutil.copy2(os.path.join(f, src_), dst)
    loads = []
    for line in open(os.path.join(f, "cases.tsv")):
        n, rc, l0, l1, t0, t1 = line.rstrip("\n").split("\t")
        loads.append({"case": n, "rc": int(rc), "load_start": float(l0), "load_end": float(l1),
                      "tctl_start": int(t0) / 1000.0, "tctl_end": int(t1) / 1000.0})
    json.dump(loads, open(os.path.join(res, tag + "-load.json"), "w"), indent=1)
    rj = json.load(open(os.path.join(jd, "result.json")))
    meta = {"backend": "kbench", "method": METHOD["kbench"], "job": job, "job_dir": jd, "host": host, "card": DEFAULT_CARD,
            "binary": binary, "binary_sha256": subprocess.check_output(["sha256sum", os.path.join(root, binary)]).decode().split()[0],
            "thermal": (rj.get("result") or {}).get("thermal"), "cases": len(cases), "cases_recorded": len(loads),
            "tctl_start_max": max((x["tctl_start"] for x in loads), default=None),
            "date": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())}
    json.dump(meta, open(os.path.join(res, tag + "-method.json"), "w"), indent=1)
    if len(loads) != len(cases):
        raise SystemExit("K ran %d of %d cases (see %s)" % (len(loads), len(cases), jd))
    return loads


def method_line(res, tag):
    """One summary line naming the host and method of a result file."""
    p = os.path.join(res, tag + "-method.json")
    if os.path.isfile(p):
        m = json.load(open(p))
        return "%s: job %s (%s), thermals %s. Method: %s." % (tag, m["job"], m["job_dir"], m.get("thermal"), m["method"])
    return "%s: %s." % (tag, METHOD["queue"])
