#!/usr/bin/env python3
"""Compute the README's numeric facts from the tree and keep them in one generated block.

    python3 tools/readme-facts.py           # rewrite the block in README.md
    python3 tools/readme-facts.py --check   # exit 1 when README.md's block differs from the tree
    python3 tools/readme-facts.py --print   # print the block, change nothing

The block sits between `<!-- facts:begin -->` and `<!-- facts:end -->` in README.md. Everything in it comes
from the tree: module and recipe counts and the origins table from catalog/ and recipes/ (via flerplib), the
warning count from `./flerp check`, the executor ABI version from include/flerp/executor.h, the strixite pin
from catalog/strixite/ORIGIN.toml and its module manifests, the module status counts from each manifest's
[gate] status, and how many Ornith champion rows configs/champions.toml holds. Prose outside the block does not repeat
these numbers, so it cannot go stale with them.
"""
import argparse
import collections
import os
import re
import subprocess
import sys
import tomllib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from flerplib.catalog import Catalog  # noqa: E402

BEGIN, END = "<!-- facts:begin -->", "<!-- facts:end -->"
README = os.path.join(ROOT, "README.md")
KINDS = ["kernel", "format", "executor", "runtime", "serve", "tool"]
STATUSES = ["benched", "parity", "builds", "harvested"]


def check_counts():
    p = subprocess.run([sys.executable, os.path.join(ROOT, "flerp"), "check"], cwd=ROOT,
                       capture_output=True, text=True)
    # the summary line: "... N error(s), W warning(s)[, C dependency cycle warning(s) inside vendored origins (...)]"
    line = next((l for l in (p.stdout + p.stderr).splitlines() if l.startswith("flerp check (catalogue):")), "")
    m = re.search(r"(\d+) error\(s\), (\d+) warning\(s\)(?:, (\d+) dependency cycle warning\(s\) inside vendored "
                  r"origins( \([^)]*\))?)?$", line)
    if not m:
        sys.exit(f"readme-facts: cannot read the counts from ./flerp check's summary line (format changed? update "
                 f"check_counts):\n{p.stdout}{p.stderr}")
    cycles = f"; {m.group(3)} dependency cycle warnings inside vendored origins{m.group(4) or ''}" if m.group(3) else ""
    return int(m.group(1)), int(m.group(2)), cycles


def abi_version():
    with open(os.path.join(ROOT, "include", "flerp", "executor.h")) as f:
        m = re.search(r"^#define\s+FLERP_EXECUTOR_ABI\s+(\d+)", f.read(), re.M)
    if not m:
        sys.exit("readme-facts: no FLERP_EXECUTOR_ABI in include/flerp/executor.h")
    return int(m.group(1))


def short(commit):
    return commit[:7] if re.fullmatch(r"[0-9a-f]{8,40}", commit or "") else (commit or "-")


def counted(counter, order):
    keys = [k for k in order if counter.get(k)] + sorted(k for k in counter if k not in order)
    return ", ".join(f"{counter[k]} {k}" for k in keys) or "-"


def champions_lines():
    with open(os.path.join(ROOT, "configs", "champions.toml"), "rb") as f:
        led = tomllib.load(f)
    out = []
    areas = list(led.get("area", {}))
    for c in sorted(led.get("champion", []), key=lambda c: areas.index(c["area"]) if c["area"] in areas else 99):
        if c.get("status") not in ("current", "measured") or not str(c.get("config", "")).startswith("ornith397"):
            continue
        case = f" ({c['case']})" if c.get("case") else ""
        out.append(f"  - {c['area']}{case}: {c['value']} {c['unit']} at {c.get('scale', '?')} scale, "
                   f"`{c['config']}`, run {c.get('run_id', '?')}, {c.get('date', '?')}, status {c['status']}")
    return out


def facts():
    cat = Catalog(ROOT)
    errors, warnings, cycles = check_counts()
    by_origin = collections.defaultdict(list)
    for m in cat.modules:
        by_origin[m.dir_origin].append(m)
    status = collections.Counter(m.gate.get("status", "none") for m in cat.modules)
    with_modules = [o for o in cat.origins() if by_origin[o]]

    sx = cat.origin_data("strixite") or {}
    sx_mods = by_origin["strixite"]
    sx_commits = collections.Counter(short(str(m.data.get("provenance", {}).get("commit", ""))) for m in sx_mods)
    sx_status = collections.Counter(m.gate.get("status", "none") for m in sx_mods)

    lines = [BEGIN,
             "<!-- generated by tools/readme-facts.py from the tree; edit the tree, then run the tool -->",
             "",
             f"- {len(cat.modules)} modules from {len(with_modules)} origins, {len(cat.recipes)} recipes; "
             f"`./flerp check` reports {errors} errors ({warnings} warnings{cycles}).",
             f"- Module status ([gate] status in each manifest): {counted(status, STATUSES)}.",
             f"- Executor ABI: version {abi_version()} (`FLERP_EXECUTOR_ABI`, `include/flerp/executor.h`).",
             f"- strixite pin: {short(sx.get('commit', ''))} (branch `{sx.get('branch', '?')}`); module manifests "
             f"by provenance commit: {counted(sx_commits, [])}; by status: {counted(sx_status, STATUSES)}.",
             f"- Ornith-1.5 397B: {len(champions_lines())} current or measured champion rows in "
             "`configs/champions.toml` (the numbers live there and in `docs/CHAMPIONS.md`, which change with "
             "every promotion; this block names only the count)."]
    lines += ["", "| origin | commit | licence | modules | by kind | by status |", "|---|---|---|---|---|---|"]
    for o in cat.origins():
        d = cat.origin_data(o) or {}
        ms = by_origin[o]
        lic = (d.get("licence") or {}).get("spdx", "-")
        lines.append(f"| `{o}` | {short(str(d.get('commit', '')))} | {lic} | {len(ms)} | "
                     f"{counted(collections.Counter(m.kind for m in ms), KINDS)} | "
                     f"{counted(collections.Counter(m.gate.get('status', 'none') for m in ms), STATUSES)} |")
    lines += ["", END]
    return "\n".join(lines)


def splice(text, block):
    i, j = text.find(BEGIN), text.find(END)
    if i < 0 or j < i:
        sys.exit(f"readme-facts: README.md has no {BEGIN} ... {END} block")
    return text[:i] + block + text[j + len(END):]


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--check", action="store_true", help="exit 1 if README.md's block is stale")
    g.add_argument("--print", action="store_true", help="print the block only")
    a = ap.parse_args()
    block = facts()
    if a.print:
        print(block)
        return 0
    with open(README) as f:
        text = f.read()
    new = splice(text, block)
    if a.check:
        if new != text:
            print("readme-facts: README.md facts block is stale; run python3 tools/readme-facts.py", file=sys.stderr)
            return 1
        print("readme-facts: README.md facts block matches the tree")
        return 0
    if new != text:
        with open(README, "w") as f:
            f.write(new)
        print("readme-facts: README.md facts block rewritten")
    else:
        print("readme-facts: README.md facts block already matches the tree")
    return 0


if __name__ == "__main__":
    sys.exit(main())
